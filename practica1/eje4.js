// Ejercicio 4: Operadores de Asignación
// Declare una variable con un valor inicial. Utilice operadores de asignación compuesta (+=,
// -=, *=) para modificar su valor y muestre cada cambio en consola.

let numero = 40;

numero += 5;
console.log('Sus valor es: ' +numero);

numero -= 5;
console.log('Sus valor es: ' +numero);

numero *= 2;
console.log('Sus valor es: ' +numero);

numero /= 2;
console.log('Sus valor es: ' +numero);
