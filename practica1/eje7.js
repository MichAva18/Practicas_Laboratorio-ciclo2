// Ejercicio 7: Cálculo de Salario con Bonificación
// Declare una variable con un salario base. Calcule una bonificación del 15% y determine el
// salario total. Muestre ambos valores en consola.


let salario = 400;
let bonificación = (salario * 0.15);
let salarioTotal = (salario + bonificación);

console.log(`Su salario es de: ${salario} \nTu salario mas bonificación es de: ${salarioTotal}`);
